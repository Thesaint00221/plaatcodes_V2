// Voor gebruik in JS-template strings: `${icoon('vink')} Opslaan`
function icoon(naam){
    return `<span class="icoon">${ICONS[naam] || ""}</span>`;
}

// Voor gebruik in statische HTML: <span class="icoon" data-icon="vink"></span>
function hydrateerIconen(){
    document.querySelectorAll("[data-icon]").forEach(el => {
        const naam = el.dataset.icon;
        if(ICONS[naam]){
            el.classList.add("icoon");
            el.innerHTML = ICONS[naam];
        }
    });
}

document.addEventListener("DOMContentLoaded", hydrateerIconen);
